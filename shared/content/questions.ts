export const questions: Question[] = Object.entries(groups).flatMap(
  ([cat, g], ci) => {
    let index = 0;
    const make = (type: Question["type"], raw: string): Question => {
      const [text, ...options] = raw.split("|");
      return {
        id: `q${ci}-${++index}`,
        cat,
        type,
        text: "{name}" + text,
        ...(options.length ? { options } : {}),
      };
    };
    return [
      ...g.choice.map((s) => make("choice", s)),
      ...g.slider.map((s) =>
        make("slider", `有多${s}？（0 = 完全不，100 = 非常）`),
      ),
      ...g.rank.map((s) => make("rank", s)),
      ...g.text.map((s) => make("text", s)),
    ];
  },
);
